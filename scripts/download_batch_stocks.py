def download_stock(code, data_dir, days=365):
    """下载单只股票"""
    try:
        end_date = datetime.now()
        start_date = end_date - timedelta(days=days)

        df = ak.stock_zh_a_hist(
            symbol=code,
            period="daily",
            start_date=start_date.strftime("%Y%m%d"),
            end_date=end_date.strftime("%Y%m%d"),
            adjust="qfq"
        )

        if df.empty:
            return False

        df = df.rename(columns={
            '日期': 'date', '开盘': 'open', '最高': 'high', '最低': 'low',
            '收盘': 'close', '成交量': 'volume', '成交额': 'amount'
        })
        df = df[['date', 'open', 'high', 'low', 'close', 'volume', 'amount']]
        df['date'] = pd.to_datetime(df['date'])
        df = df.sort_values('date').tail(days)

        output_file = data_dir / f'stock_{code}.csv'
        df.to_csv(output_file, index=False, encoding='utf-8-sig')
        return True

    except Exception as e:
        print(f"    错误: {str(e)[:50]}")
        return False


def main():
    """主函数"""
    import argparse
    parser = argparse.ArgumentParser(description='批量下载A股数据')
    parser.add_argument('--batch', type=int, help='指定批次号(1-7)')
    parser.add_argument('--all', action='store_true', help='下载所有批次')
    args = parser.parse_args()

    data_dir = PROJECT_ROOT / 'data' / 'stocks'
    data_dir.mkdir(parents=True, exist_ok=True)

    if args.batch:
        # 下载指定批次
        if 1 <= args.batch <= len(BATCHES):
            codes = BATCHES[args.batch - 1]
            print(f"下载批次 {args.batch}: {len(codes)} 只股票")
            for i, code in enumerate(codes):
                print(f"[{i+1}/{len(codes)}] {code}...", end=' ')
                if download_stock(code, data_dir):
                    print("OK")
                else:
                    print("FAIL")
                time.sleep(2)
        else:
            print(f"批次号必须在 1-{len(BATCHES)} 之间")
    elif args.all:
        # 下载所有批次
        total = sum(len(b) for b in BATCHES)
        print(f"下载所有批次: 共 {total} 只股票")

        for batch_idx, codes in enumerate(BATCHES):
            print(f"\n=== 批次 {batch_idx + 1}/{len(BATCHES)} ===")
            for i, code in enumerate(codes):
                print(f"[{i+1}/{len(codes)}] {code}...", end=' ')
                if download_stock(code, data_dir):
                    print("OK")
                else:
                    print("FAIL")
                time.sleep(2)
    else:
        print("使用方法:")
        print("  python download_batch_stocks.py --batch 1  # 下载第1批")
        print("  python download_batch_stocks.py --all      # 下载所有批次")


if __name__ == '__main__':
    main()
